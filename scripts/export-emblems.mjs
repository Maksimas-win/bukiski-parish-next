// Exports the emblem set as one SVG sprite for sites that do not run this
// build (bukiski-hram.org references it through <use href="…#em-name">).
// External sprites cannot be styled from the page, so gradient stops, shadow
// and depth colours are written as attributes with the light-theme values.
//
//   node scripts/export-emblems.mjs > ../bukiski-hram-org/assets/img/emblems.svg

import { emblem, emblemNames } from './lib/icons.mjs';

const STOPS = {
  wine: ['#8a2230', '#42080f'], gilt: ['#f1dca4', '#a97f33'], dome: ['#3b6f84', '#0f2832'],
  cream: ['#fffaf0', '#e3d4b4'], ink: ['#5d6a72', '#1a2227'], flame: ['#ffd97d', '#d9611c']
};
const defs = Object.entries(STOPS).map(([id, [a, b]]) =>
  `<linearGradient id="em-${id}" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="${a}"/><stop offset="1" stop-color="${b}"/></linearGradient>`).join('')
  + '<radialGradient id="em-gloss" cx="0.3" cy="0.2" r="0.9"><stop offset="0" stop-color="#fff" stop-opacity="0.55"/><stop offset="1" stop-color="#fff" stop-opacity="0"/></radialGradient>'
  + '<filter id="em-blur" x="-30%" y="-80%" width="160%" height="260%"><feGaussianBlur stdDeviation="1.6"/></filter>';

const symbols = emblemNames().map(name => {
  const inner = String(emblem(name))
    .replace(/^<svg[^>]*>/, '').replace(/<\/svg>$/, '')
    .replace(/class="em-shadow"/g, 'fill="#140a05" fill-opacity="0.18"')
    .replace(/class="em-depth"/g, 'fill="#1e0e08" fill-opacity="0.3"')
    .replace(/class="em-depth-stroke"/g, 'stroke="#1e0e08" stroke-opacity="0.3"');
  return `<symbol id="em-${name}" viewBox="0 0 64 64">${inner}</symbol>`;
}).join('\n');

process.stdout.write(`<svg xmlns="http://www.w3.org/2000/svg">\n<!-- Generated by scripts/export-emblems.mjs in bukiski-parish-next; edit scripts/lib/icons.mjs there. -->\n<defs>${defs}</defs>\n${symbols}\n</svg>\n`);
