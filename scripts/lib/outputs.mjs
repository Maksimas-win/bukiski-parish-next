// Non-HTML outputs: crawler files, host configuration, calendar and contact files.

import { icsCalendar } from '../../assets/js/domain.js';
import { contentSecurityPolicy } from './layout.mjs';

const securityHeaders = site => [
  ['Content-Security-Policy', `${contentSecurityPolicy(site)}; frame-ancestors 'none'`],
  ['X-Content-Type-Options', 'nosniff'],
  ['Referrer-Policy', 'strict-origin-when-cross-origin'],
  ['X-Frame-Options', 'DENY'],
  ['Permissions-Policy', 'camera=(), microphone=(), geolocation=(), payment=()']
];

// CSS and JS are requested with a ?v=<hash> query that changes whenever their
// content does, so they may be cached for a long time. HTML and data must be
// revalidated so that a new schedule is seen at once.
const CACHE_RULES = [
  ['html|json|ics|vcf|xml|txt', 'no-cache'],
  ['css|js|woff2', 'public, max-age=31536000, immutable'],
  ['webp|jpg|jpeg|png|gif|svg', 'public, max-age=2592000']
];

const regexEscape = value => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const withoutRoot = redirects => redirects.filter(redirect => redirect.from !== '/');

export function sitemap(site, routes) {
  const urls = [...routes].filter(([path, route]) => !route.noindex && path === route.canonicalPath);
  const escapeXML = value => value.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
  return `<?xml version="1.0" encoding="UTF-8"?><urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">${urls.map(([path]) => `<url><loc>${escapeXML(site.canonical(path))}</loc></url>`).join('')}</urlset>`;
}

/**
 * Preview builds block every crawler. Production allows crawling of everything:
 * pages that must stay out of search carry `noindex`, which a crawler can only
 * obey if it is allowed to fetch the page.
 */
export function robots(site) {
  return site.production
    ? `User-agent: *\nAllow: /\nSitemap: ${site.canonical('/sitemap.xml')}\n`
    : 'User-agent: *\nDisallow: /\n';
}

/** Apache configuration for the new site. */
export function htaccess(site, redirects) {
  const { base } = site;
  const headers = securityHeaders(site).map(([name, value]) => `Header always set ${name} "${value}"`).join('\n');
  const caching = CACHE_RULES.map(([extensions, value]) => `<FilesMatch "\\.(${extensions})$">\nHeader set Cache-Control "${value}"\n</FilesMatch>`).join('\n');
  const documents = site.documentDelivery === 'direct'
    ? '<FilesMatch "\\.(pdf|doc)$">\nHeader set X-Robots-Tag "noindex, nofollow"\n</FilesMatch>\n'
    : '';
  const rules = withoutRoot(redirects).map(({ from, to }) => `RewriteRule ^${regexEscape(from.slice(1))}/?$ ${base}${to} [R=301,L,NE]`).join('\n');
  return `Options -Indexes\n<IfModule mod_headers.c>\n${headers}\n${caching}\n${documents}</IfModule>\n\n<IfModule mod_rewrite.c>\nRewriteEngine On\nRewriteRule (^|/)\\.git(?:/|$) - [F,L,NC]\n${rules}\n</IfModule>\nErrorDocument 404 ${base}/404.html\n`;
}

/**
 * Redirects to install on bukiski-hram.org once the new site is live on the
 * production address. Paths of the .org site are preserved by the new site, so
 * every request moves to the same path there. /data/ is left alone: the
 * current .org site still publishes the schedule feed the new site reads.
 */
export function orgDomainHtaccess(site) {
  const target = site.productionOrigin;
  if (new URL(target).hostname === 'bukiski-hram.org') throw new Error('The .org redirect file is only for a site whose production address is not bukiski-hram.org');
  return [
    '# Install ONLY on bukiski-hram.org, after the new site is live and checked.',
    `# Generated by scripts/build.mjs from content/settings.json (origin: ${target}).`,
    'RewriteEngine On',
    '# Keep the schedule feed until its generator has moved (see docs/DEPLOYMENT.md).',
    'RewriteCond %{REQUEST_URI} !^/data/',
    `RewriteRule ^(.*)$ ${target}/$1 [R=301,L,NE]`,
    ''
  ].join('\n');
}

/** Cloudflare Pages / Netlify style headers. */
export function headersFile(site) {
  const security = securityHeaders(site).map(([name, value]) => `  ${name}: ${value}`).join('\n');
  return `/*\n${security}\n\n${site.base}/*.html\n  Cache-Control: no-cache\n\n${site.base}/assets/data/*\n  Cache-Control: no-cache\n`;
}

export function redirectsFile(site, redirects) {
  const { base } = site;
  return `${withoutRoot(redirects).map(({ from, to }) => `${base}${from} ${base}${to} 301\n${base}${from}/ ${base}${to} 301`).join('\n')}\n`;
}

export function scheduleCalendar(site, lang) {
  const t = site.locales[lang];
  return icsCalendar({
    events: site.schedule.events.map(event => ({ id: event.id, start: event.start, title: event.title[lang], subtitle: event.subtitle[lang] || '' })),
    lang,
    name: t.name,
    location: site.settings.address,
    note: t.calendarNote,
    stamp: site.schedule.sourceUpdatedAt,
    uidDomain: new URL(site.productionOrigin).hostname
  });
}

export function contactCard(site) {
  const { legalName, phone, addressParts } = site.settings;
  const escape = value => String(value).replace(/\\/g, '\\\\').replace(/,/g, '\\,').replace(/;/g, '\\;');
  return [
    'BEGIN:VCARD',
    'VERSION:3.0',
    `FN:${escape(legalName)}`,
    `ORG:${escape(legalName)}`,
    `TEL;TYPE=WORK,VOICE:${phone}`,
    `ADR;TYPE=WORK:;;${escape(addressParts.street)};${escape(addressParts.locality)};;${escape(addressParts.postalCode)};${escape(addressParts.country)}`,
    `URL:${site.canonical('/')}`,
    'END:VCARD',
    ''
  ].join('\r\n');
}

/** Full article text for the optional in-browser search. Loaded only on request. */
export function searchIndex(catalog) {
  return catalog.articlesFor('ru').map(entry => ({
    u: entry.target,
    l: entry.language,
    x: entry.page.text.replace(/\s+/g, ' ').trim()
  }));
}

export function migrationCSV(inventory) {
  const cell = value => `"${String(value ?? '').replaceAll('"', '""')}"`;
  const fields = Object.keys(inventory[0]);
  return `\uFEFF${fields.join(',')}\n${inventory.map(row => fields.map(field => cell(row[field])).join(',')).join('\n')}`;
}
